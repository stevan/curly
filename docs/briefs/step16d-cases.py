#!/usr/bin/env python3
"""Writes runtime/cases16d.c, perl 5.42's own case mapping and quotemeta past
ASCII (step 16d, D257), from perl itself: for every character from U+0080 to
U+10FFFF but the surrogates, what `uc`, `lc`, `ucfirst`, `lcfirst` and
`quotemeta` of that one character give, under `use v5.42;` (whose bundle
has unicode_strings), wherever it is not the character itself. Nothing is
written from memory or from a Unicode table of another version: the table
is perl's answer, and a new perl is met by running this again.

    python3 docs/briefs/step16d-cases.py           # writes runtime/cases16d.c
    python3 docs/briefs/step16d-cases.py --check   # the file is what perl gives now

It also asks perl the two things the runtime leans on: that each function of
a string is the function of each character in turn, joined (no final sigma,
no context), over random strings; and that `ucfirst` and `lcfirst` touch the
first character alone.
"""
import os
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
PERL = os.environ.get('CURLY_PERL', 'perl')
OUT = os.path.join(ROOT, 'runtime', 'cases16d.c')

DUMP = r'''
use v5.42;
binmode STDOUT;
for my $c (0x80 .. 0x10FFFF) {
    next if $c >= 0xD800 && $c <= 0xDFFF;
    my $s = chr($c);
    for my $f (['uc', uc $s], ['lc', lc $s], ['ucfirst', ucfirst $s], ['lcfirst', lcfirst $s]) {
        next if $f->[1] eq $s;
        say join ' ', $f->[0], sprintf('%X', $c), map { sprintf '%X', ord } split //, $f->[1];
    }
    # T675: uc moves a U+0345 past every mark that follows it, and makes
    # one of two with only marks between: which characters those are.
    if (uc("\x{345}" . $s) ne "\x{399}" . uc($s)) {
        die "uc of U+0345 and $c is neither order" unless $c == 0x345 || uc("\x{345}" . $s) eq uc($s) . "\x{399}";
        say "mark ", sprintf('%X', $c);
    }
    my $q = quotemeta $s;
    if ($q ne $s) {
        die "quotemeta of $c is not a backslash and the character" unless $q eq "\\" . $s;
        say "quotemeta ", sprintf('%X', $c);
    }
}
'''

# Each function of a string is that function of its characters, joined; and
# ucfirst and lcfirst change the first character and nothing else. But for
# one thing (T664, T675): perl's uc moves a U+0345 past the marks that
# follow it, and gives one U+0399 for two with only marks between. The
# runtime faults on a U+0345 before a mark, and the pool here has a U+0345
# before a letter, and a mark after a letter, and never the two together.
AGREE = r'''
use v5.42;
srand(42);
my @pool = (0x41, 0x61, 0xDF, 0x130, 0x131, 0x3A3, 0x3C2, 0x3C3, 0x390, 0x1C4, 0x1C5, 0x1C6, 0xFB03, 0x149, 0x3B9, 0x10400, 0x10428, 0x20, 0x2E, 0xE9, 0xC9, 0x1E9E, 0x2126, 0x212A);
my $bad = 0;
for my $n (1 .. 20000) {
    my $s = join '', map { chr $pool[rand @pool] } 1 .. 1 + int rand 6;
    $s .= "\x{345}a\x{345}" if $n % 7 == 0;
    $s .= "a\x{301}\x{345}b\x{300}" if $n % 11 == 0;
    my @c = split //, $s;
    $bad++ if uc $s ne join '', map { uc } @c;
    $bad++ if lc $s ne join '', map { lc } @c;
    $bad++ if quotemeta $s ne join '', map { quotemeta } @c;
    $bad++ if ucfirst $s ne ucfirst($c[0]) . join '', @c[1 .. $#c];
    $bad++ if lcfirst $s ne lcfirst($c[0]) . join '', @c[1 .. $#c];
}
say $bad;
'''


def perl(code):
    return subprocess.run([PERL, '-e', code], capture_output=True, check=True).stdout.decode()


def generate():
    agree = perl(AGREE).strip()
    if agree != '0':
        sys.exit(f'perl does not map a string a character at a time: {agree} differences')
    maps = {'uc': [], 'lc': [], 'ucfirst': [], 'lcfirst': []}
    quote = []
    marks = []
    for line in perl(DUMP).splitlines():
        f, *rest = line.split()
        if f == 'mark':
            marks.append(int(rest[0], 16))
            continue
        if f == 'quotemeta':
            quote.append(int(rest[0], 16))
            continue
        cp, *out = [int(x, 16) for x in rest]
        if len(out) > 3:
            sys.exit(f'{f} of U+{cp:04X} is {len(out)} characters, more than the table holds')
        maps[f].append((cp, out))
    def spans(cps):
        out = []
        for cp in cps:
            if out and out[-1][1] == cp - 1:
                out[-1][1] = cp
            else:
                out.append([cp, cp])
        return out
    ranges = spans(quote)
    if any(cp < 0x80 for cp in marks) or 0x345 not in marks:
        sys.exit('the characters uc moves a U+0345 past are not what the runtime takes them for')
    version = perl('print $^V').strip()
    lines = [
        '// GENERATED by docs/briefs/step16d-cases.py from perl ' + version + ' itself: do not edit.',
        '// perl\'s uc, lc, ucfirst, lcfirst and quotemeta of each character past ASCII',
        '// that they change (step 16d, D257). A string is mapped a character at a',
        '// time, which the generator asked perl too. Included by rt.c.',
        '',
        'typedef struct { uint32_t from; uint8_t count; uint32_t to[3]; } rt_case;',
        '',
    ]
    for f, rows in maps.items():
        lines.append(f'static const rt_case case_{f}[{len(rows)}] = {{')
        for cp, out in rows:
            to = ', '.join(f'0x{x:X}' for x in out + [0] * (3 - len(out)))
            lines.append(f'    {{ 0x{cp:X}, {len(out)}, {{ {to} }} }},')
        lines.append('};')
        lines.append('')
    lines.append(f'// The characters past ASCII quotemeta puts a backslash before, as ranges.')
    lines.append(f'static const uint32_t case_quoted[{len(ranges)}][2] = {{')
    for a, b in ranges:
        lines.append(f'    {{ 0x{a:X}, 0x{b:X} }},')
    lines.append('};')
    lines.append('')
    lines.append(f'// The characters uc moves a U+0345 before them past (perl\'s marks, T675), as ranges.')
    lines.append(f'static const uint32_t case_mark[{len(spans(marks))}][2] = {{')
    for a, b in spans(marks):
        lines.append(f'    {{ 0x{a:X}, 0x{b:X} }},')
    lines.append('};')
    return '\n'.join(lines) + '\n', {f: len(r) for f, r in maps.items()}, len(quote), len(ranges)


if __name__ == '__main__':
    text, counts, quoted, ranges = generate()
    if '--check' in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print('runtime/cases16d.c is what perl gives' if same else 'runtime/cases16d.c differs from what perl gives')
        sys.exit(0 if same else 1)
    open(OUT, 'w').write(text)
    print(f'wrote {OUT}: {counts}, quotemeta {quoted} characters in {ranges} ranges')
