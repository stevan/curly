#!/usr/bin/env python3
# Writes the tables of runtime/regex.c that say which characters perl's
# \d, \w and \s match (step 19; D226, T545, T67), by asking perl itself,
# under `use v5.42;`, of every character there is, the surrogates aside
# (no string holds one, D42). The tables are perl's, whatever version of
# Unicode it has; rerun this with a new perl, and `make test`.
#
#     python3 docs/briefs/step19-tables.py
import os
import re
import subprocess

PERL = os.environ.get('CURLY_PERL', 'perl')
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
PROGRAM = r'''use v5.42;
for my $name (qw(d w s)) {
    my $re = $name eq 'd' ? qr/\d/ : $name eq 'w' ? qr/\w/ : qr/\s/;
    my ($in, $from) = (0, 0);
    my @out;
    for my $c (0 .. 0x10FFFF) {
        my $m = ($c >= 0xD800 && $c <= 0xDFFF) ? 0 : (chr($c) =~ $re ? 1 : 0);
        if ($m && !$in) { $from = $c; $in = 1 }
        elsif (!$m && $in) { push @out, sprintf("0x%X, 0x%X", $from, $c - 1); $in = 0 }
    }
    push @out, sprintf("0x%X, 0x%X", $from, 0x10FFFF) if $in;
    print "$name ", join(", ", @out), "\n";
}
'''
out = subprocess.run([PERL, '-e', PROGRAM], capture_output=True, text=True, check=True).stdout
version = subprocess.run([PERL, '-MUnicode::UCD', '-e', 'print Unicode::UCD::UnicodeVersion()'], capture_output=True, text=True, check=True).stdout
lines = [f'// Generated by docs/briefs/step19-tables.py from perl {subprocess.run([PERL, "-e", "print $^V"], capture_output=True, text=True).stdout}, Unicode {version}: do not edit.']
for row in out.strip().split('\n'):
    name, ranges = row.split(' ', 1)
    nums = ranges.split(', ')
    lines.append(f'static const uint32_t RE_{name.upper()}[] = {{')
    for k in range(0, len(nums), 8):
        lines.append('    ' + ', '.join(nums[k:k + 8]) + ',')
    lines.append('};')
table = '\n'.join(lines)
path = os.path.join(ROOT, 'runtime', 'regex.c')
src = open(path, encoding='utf-8').read()
new, n = re.subn(r'(// ---- tables\n).*?(\n// ---- end of tables)', lambda m: m.group(1) + table + m.group(2), src, flags=re.S)
assert n == 1, 'the markers in runtime/regex.c'
open(path, 'w', encoding='utf-8').write(new)
print(f'{path}: {", ".join(r.split(" ", 1)[0] + " " + str(len(r.split(", ")) // 2) for r in out.strip().split(chr(10)))} ranges')
