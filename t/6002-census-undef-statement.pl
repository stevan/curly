# undef of a variable, an element, an array, a hash and through a reference, as the assignment it is (D252).
use v5.42;
my @a = (1);
undef $a[3];
say scalar @a;
my %h;
undef $h{k};
say exists $h{k} ? "e" : "n";
my $x = 3;
undef $x;
say defined $x ? "d" : "u";
my @b = (1, 2);
undef @b;
say scalar @b;
my %g = (a => 1);
undef(%g);
say scalar %g;
my $r = [1, 2];
undef $r->@*;
say scalar $r->@*;
undef $r->[5];
say scalar $r->@*;
my $u;
undef $u->[1];
say ref $u;
my $v;
undef %{$v};
say ref $v;
my $w;
undef @{$w};
say ref $w;
my $s = \$x;
$x = 1;
undef $s->$*;
say defined $x ? "d" : "u";
$x = 2;
undef ${$s};
say defined $x ? "d" : "u";
$x = 3;
undef $x if $x > 2;
say defined $x ? "d" : "u";
my $c = 4;
my $k = sub { $c // "u" };
undef $c;
say $k->();
my $n = {a => {b => 1}};
undef $n->{a}{b};
say exists $n->{a}{b} ? "e" : "n";
sub clear() {
    my $y = 1;
    undef $y;
}
clear();
say "ok";
