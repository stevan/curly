#define RE_TABLE(t) (t), sizeof(t) / sizeof((t)[0]) / 2

// Whether `c` is in a table of ranges, each a first and a last.
static int re_in(const uint32_t *t, size_t n, uint32_t c) {
    size_t lo = 0, hi = n;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (c < t[2 * mid]) hi = mid;
        else if (c > t[2 * mid + 1]) lo = mid + 1;
        else return 1;
    }
    return 0;
}

static int re_word(uint32_t c) {
    return re_in(RE_TABLE(RE_W), c);
}

typedef struct {
    rt_ctx *cx;
    const rt_regex *re;
    const char *s;
    int64_t len;
    int64_t *caps;      // 2 per group, the whole match first: a start and an end, or -1
    int64_t *stack;     // 3 a frame: a pc and a position, or -1 - slot and what it held
    uint64_t sp, room;
    uint64_t steps;
    int64_t *found;     // under /g, every match's captures, one after another
    uint64_t nfound, found_room;
} re_run;

static void re_free(re_run *m) {
    free(m->caps);
    free(m->stack);
    free(m->found);
}

static void re_fault(re_run *m, const char *what) __attribute__((noreturn));
static void re_fault(re_run *m, const char *what) {
    re_free(m);
    rt_fault(m->cx, what);
}

static void re_push(re_run *m, int64_t a, int64_t b) {
    if (m->sp + 2 >= m->room) {
        uint64_t room = m->room ? m->room * 2 : 192;
        int64_t *grown = realloc(m->stack, room * sizeof(int64_t));
        if (grown == NULL) re_fault(m, "out of memory");
        m->stack = grown;
        m->room = room;
    }
    m->stack[m->sp++] = a;
    m->stack[m->sp++] = b;
}

// The character before byte `at`, or -1 at the start.
static int64_t re_before(const char *s, int64_t at) {
    if (at == 0) return -1;
    int64_t k = at - 1;
    while (k > 0 && continues(s[k])) k--;
    int size;
    return decode(s + k, &size);
}

static int re_class(const rt_regex *re, int32_t off, uint32_t c) {
    const int32_t *row = re->classes + off;
    int32_t flags = row[0], n = row[1];
    int in = 0;
    for (int32_t k = 0; k < n && !in; k++) in = c >= (uint32_t)row[2 + 2 * k] && c <= (uint32_t)row[3 + 2 * k];
    if (!in && (flags & 2)) in = re_in(RE_TABLE(RE_D), c);
    if (!in && (flags & 4)) in = re_word(c);
    if (!in && (flags & 8)) in = re_in(RE_TABLE(RE_S), c);
    if (!in && (flags & 16)) in = !re_in(RE_TABLE(RE_D), c);
    if (!in && (flags & 32)) in = !re_word(c);
    if (!in && (flags & 64)) in = !re_in(RE_TABLE(RE_S), c);
    return (flags & 1) ? !in : in;
}

// One try, from byte `start`: 1 if the program matches there, the
// captures in `m->caps`. A match that ends at `notempty` and is of no
// length is no match, and the machine backtracks from it: after a match
// of no length a `/g` may not find another where it ended (T544).
static int re_try(re_run *m, int64_t start, int64_t notempty) {
    const int32_t *code = m->re->code;
    const char *s = m->s;
    int64_t len = m->len;
    for (int32_t k = 0; k < 2 * (m->re->groups + 1); k++) m->caps[k] = -1;
    m->sp = 0;
    int64_t pc = 0, pos = start;
    for (;;) {
        if (++m->steps > RE_STEPS) re_fault(m, "pattern match too long");
        int size = 0;
        uint32_t c = 0;
        switch (code[pc]) {
        case RE_CHAR:
            if (pos < len && (c = decode(s + pos, &size)) == (uint32_t)code[pc + 1]) { pos += size; pc += 2; continue; }
            goto fail;
        case RE_CHARI:
            if (pos < len) {
                c = decode(s + pos, &size);
                if (c >= 'A' && c <= 'Z') c |= 0x20;
                if (c == (uint32_t)code[pc + 1]) { pos += size; pc += 2; continue; }
            }
            goto fail;
        case RE_ANY:
            if (pos < len && s[pos] != '\n') { decode(s + pos, &size); pos += size; pc += 1; continue; }
            goto fail;
        case RE_ANYNL:
            if (pos < len) { decode(s + pos, &size); pos += size; pc += 1; continue; }
            goto fail;
        case RE_CLASS:
            if (pos < len && re_class(m->re, code[pc + 1], (c = decode(s + pos, &size)))) { pos += size; pc += 2; continue; }
            goto fail;
        case RE_BOL:
            if (pos == 0) { pc += 1; continue; }
            goto fail;
        case RE_MBOL:
            // Not after the newline that ends the string (T549).
            if (pos == 0 || (s[pos - 1] == '\n' && pos < len)) { pc += 1; continue; }
            goto fail;
        case RE_EOL:
            if (pos == len || (pos == len - 1 && s[pos] == '\n')) { pc += 1; continue; }
            goto fail;
        case RE_MEOL:
            if (pos == len || s[pos] == '\n') { pc += 1; continue; }
            goto fail;
        case RE_EOS:
            if (pos == len) { pc += 1; continue; }
            goto fail;
        case RE_WORDB:
        case RE_NWORDB: {
            int64_t b = re_before(s, pos);
            int left = b >= 0 && re_word((uint32_t)b);
            int right = pos < len && re_word(decode(s + pos, &size));
            if ((left != right) == (code[pc] == RE_WORDB)) { pc += 1; continue; }
            goto fail;
        }
        case RE_SPLIT:
            re_push(m, code[pc + 2], pos);
            pc = code[pc + 1];
            continue;
        case RE_JMP:
            pc = code[pc + 1];
            continue;
        case RE_SAVE: {
            int32_t slot = code[pc + 1];
            re_push(m, -1 - slot, m->caps[slot]);
            m->caps[slot] = pos;
            pc += 2;
            continue;
        }
        case RE_BACKREF:
        case RE_BACKREFI: {
            int32_t g = code[pc + 1];
            int64_t from = m->caps[2 * g], to = m->caps[2 * g + 1];
            if (from < 0 || to < 0) goto fail;
            int64_t n = to - from;
            if (pos + n > len) goto fail;
            int same = 1;
            for (int64_t k = 0; k < n && same; k++) {
                char x = s[from + k], y = s[pos + k];
                if (code[pc] == RE_BACKREFI) {
                    if (x >= 'A' && x <= 'Z') x = (char)(x | 0x20);
                    if (y >= 'A' && y <= 'Z') y = (char)(y | 0x20);
                }
                same = x == y;
            }
            if (!same) goto fail;
            pos += n;
            pc += 2;
            continue;
        }
        case RE_MATCH:
            if (pos == notempty && m->caps[0] == pos) goto fail;
            return 1;
        default:
            rt_fault(m->cx, "internal: a pattern's program is broken");
        }
    fail:
        for (;;) {
            if (m->sp == 0) return 0;
            int64_t b = m->stack[--m->sp];
            int64_t a = m->stack[--m->sp];
            if (a < 0) {
                m->caps[-1 - a] = b;
                continue;
            }
            pc = a;
            pos = b;
            break;
        }
    }
}

// The first match from byte `from` on, trying each start in turn.
static int re_search(re_run *m, int64_t from, int64_t notempty) {
    for (int64_t at = from; at <= m->len;) {
        if (re_try(m, at, notempty)) return 1;
        if (at == m->len) break;
        int size;
        decode(m->s + at, &size);
        at += size;
    }
    return 0;
}

static void re_begin(rt_ctx *cx, re_run *m, const rt_regex *re, const rt_str *s) {
    // /i is ASCII's (D230): perl folds a character past ASCII by
    // Unicode's tables, one to two (T546).
    if (re->icase && s->len != s->chars) rt_fault(cx, "a match without regard to case of a string with a character past ASCII");
    memset(m, 0, sizeof *m);
    m->cx = cx;
    m->re = re;
    m->s = s->bytes;
    m->len = (int64_t)s->len;
    m->caps = malloc(sizeof(int64_t) * 2 * (size_t)(re->groups + 1));
    if (m->caps == NULL) rt_fault(cx, "out of memory");
}

rt_value rt_match(rt_ctx *cx, const rt_regex *re, rt_value subject) {
    scratch x;
    const rt_str *s = to_str(cx, subject, &x);
    re_run m;
    re_begin(cx, &m, re, s);
    int found = re_search(&m, 0, -1);
    re_free(&m);
    return rt_bool(found);
}

rt_value rt_match_not(rt_ctx *cx, const rt_regex *re, rt_value subject) {
    return rt_bool(!rt_match(cx, re, subject).as.i);
}

// The string between two bytes of the subject, made on the heap: the one
// allocation, after which the subject is read again.
static rt_value re_piece(rt_ctx *cx, const rt_str *subject, int64_t from, int64_t to) {
    if (from < 0 || to < 0) return rt_undef();
    uint64_t chars = 0;
    for (int64_t k = from; k < to; k++) chars += !continues(subject->bytes[k]);
    char *bytes;
    const rt_str *piece = str_new(cx, (uint64_t)(to - from), chars, &bytes);
    subject = alive(cx, subject);
    if (to > from) memcpy(bytes, subject->bytes + from, (size_t)(to - from));
    return rt_string(piece);
}

// A match where a list is wanted (D235): with no group `(1)`, with groups
// what each captured; under /g every match's, each one's captures or,
// with no group, what it matched; nothing when there is no match.
void rt_match_list(rt_ctx *cx, rt_value list, const rt_regex *re, rt_value subject) {
    scratch x;
    const rt_str *s = to_str(cx, subject, &x);
    re_run m;
    re_begin(cx, &m, re, s);
    int32_t groups = re->groups;
    // What each match leaves: its captures' bounds, the whole match's
    // aside unless there is no group.
    int32_t width = groups == 0 ? 2 : 2 * groups;
    int64_t from = 0, notempty = -1;
    while (re_search(&m, from, notempty)) {
        if (m.nfound + (uint64_t)width > m.found_room) {
            uint64_t room = m.found_room ? m.found_room * 2 : 16 * (uint64_t)width;
            int64_t *grown = realloc(m.found, room * sizeof(int64_t));
            if (grown == NULL) re_fault(&m, "out of memory");
            m.found = grown;
            m.found_room = room;
        }
        for (int32_t k = 0; k < width; k++) m.found[m.nfound++] = m.caps[groups == 0 ? k : 2 + k];
        if (!re->global) break;
        from = m.caps[1];
        notempty = m.caps[0] == m.caps[1] ? m.caps[1] : -1;
        if (from > m.len) break;
    }
    // (The machine's own memory goes before anything is made.)
    int64_t *found = m.found;
    uint64_t nfound = m.nfound;
    m.found = NULL;
    re_free(&m);
    if (nfound > 0 && groups == 0 && !re->global) {
        free(found);
        rt_list_add(cx, list, rt_bool(1));
        return;
    }
    // A string made here may set a collection off: the list is in a slot,
    // and each piece goes into it as it is made. (A fault for want of
    // memory ends the program with the offsets still on this stack.)
    for (uint64_t k = 0; k < nfound; k += 2) {
        rt_value piece = re_piece(cx, s, found[k], found[k + 1]);
        rt_list_add(cx, list, piece);
    }
    free(found);
}
