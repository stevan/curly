// program compiler/src/regex.ts made of a pattern. A backtracking machine
// with a stack of its own: a SPLIT pushes the alternative it did not take,
// a SAVE pushes what a capture held before, and a failure pops back to the
// last alternative, putting captures back on the way. So the order of
// trying is perl's: the leftmost start, the first alternative, a greedy
// count the most first and a lazy one the fewest; and what each group
